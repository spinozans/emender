"""Replay C9 byte receipts, denominators, OOD counts and novelty independently."""
import json
import hashlib
import numpy as np
from .c9 import OUT, ROOT, sha, novelty, runs

def main():
    binding=json.loads((OUT/'binding.json').read_text())
    result=json.loads((OUT/'results.json').read_text())
    samples=json.loads((OUT/'samples.json').read_text())
    assert binding['protocol_sha256']==sha(ROOT/'PREREGISTRATION_C9.md')
    assert binding['code_sha256']==sha(ROOT/'c9.py')
    assert result['samples_sha256']==sha(OUT/'samples.json')
    assert len(samples)==len(result['results'])==8
    for row,sample in zip(result['results'],samples):
        data=bytes.fromhex(sample['hex'])
        assert len(data)==1024 and hashlib.sha256(data).hexdigest()==row['sha256']
        assert sample['text']==data.decode('utf8',errors='replace')
        steps=json.loads((OUT/f"{row['mode']}_{row['prompt']}_steps.json").read_text())
        assert bytes(s['byte'] for s in steps)==data
        assert row['self_nll']==float(np.mean([s['nll'] for s in steps]))
        flags=[s['empty_full_context'] for s in steps]
        assert row['full_context_empty_runs']==runs(flags)
        assert row['full_context_empty_steps']==sum(flags)
        assert row['full_context_reentries']==sum(flags[k-1] and not flags[k] for k in range(1,len(flags)))
        assert row['departures']==sum(s['departure'] for s in steps)
        assert row['forced_steps']==sum(s['forced'] for s in steps)
        assert row['fork_steps']==sum(s['support']>1 for s in steps)
        assert row['suffix_backoff_successes']==sum(s['empty_full_context'] and s['support']>0 for s in steps)
        assert all(not s['departure'] for s in steps if s['forced'])
    raw=(ROOT/'input.txt').read_bytes()
    for mode in ('neural_only','walk_fork'):
        ss=[bytes.fromhex(s['hex']) for s in samples if s['mode']==mode]
        assert novelty(ss,raw[:int(.9*len(raw))])==result['novelty'][mode]['train']
        assert novelty(ss,raw)==result['novelty'][mode]['whole_input']
    print(json.dumps(dict(status='green',samples=8,generated_bytes=8192,n_values=list(range(4,33)),
        checks=['sample hashes','generated bytes','OOD runs and reentries','all novelty denominators replayed'])))
if __name__=='__main__':
    main()
