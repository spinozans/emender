"""Persistent CPU reference decoder for a trained natural-text positional router.

One document per instance; predict() never appends. observe() is writer-only.
"""
import argparse
from collections import Counter
import json
from pathlib import Path
import time

import numpy as np
import torch
from .xsa_binding_live import Session
from .xsa_controller import Controller
from .xsa_controller_data import digest
from .xsa_natural_position import HERE, GRID, Router, evidence, summarize


class PositionalDecoder:
    def __init__(self, exe, bundle):
        result=json.loads((bundle/'result.json').read_text());base=HERE/'receipts/xsa_controller_v1/controller.pt';ck=bundle/'router.pt'
        if [digest(p) for p in (exe,base,ck)]!=[result['engine'],result['base_sha'],result['checkpoint_sha']]:raise ValueError('decoder hash mismatch')
        self.base=Controller().eval();self.base.load_state_dict(torch.load(base,weights_only=True));self.router=Router(5).eval();self.router.load_state_dict(torch.load(ck,weights_only=True));self.server=Session(exe);self.pos=0;self.tail=b''

    def close(self): self.server.close()

    def observe(self,data):
        if not data:return
        for i in range(0,len(data),65536):
            b=data[i:i+65536];new=self.pos+len(b)
            if self.server.rpc('append '+b.hex())!={'visible':new}:raise RuntimeError('append offset mismatch')
            if new//512>self.pos//512:
                if self.server.rpc('seal')!={'sealed':new}:raise RuntimeError('seal offset mismatch')
            self.pos=new;self.tail=(self.tail+b)[-64:]

    @torch.no_grad()
    def predict(self):
        if self.pos<16:raise ValueError('model needs >=16 observed bytes')
        z=self.base.encoder(self.base.embedding(torch.tensor([list(self.tail[-16:])])).flatten(1));q=self.base.head(z).double().softmax(1)[0].numpy();calls=Counter()
        def rpc(cmd):
            a=self.server.rpc(cmd);calls[cmd.split()[0]]+=1;return a
        h,_,trace=evidence(rpc,self.tail,self.pos);f,_=summarize(h,q,0);w=self.router(z,torch.tensor([f],dtype=torch.float32))[0].numpy();p=np.zeros(256)
        for weight,counts in zip(w,h):
            c=q.copy()
            for b,n in counts.items():c[b]+=n
            p+=weight*c/(1+counts.total())
        if not np.isclose(p.sum(),1):raise RuntimeError('unnormalized prediction')
        return p,dict(visible=self.pos,weights=dict(zip(GRID,map(float,w))),anchors=trace,work=dict(calls))


def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('exe',type=Path);ap.add_argument('bundle',type=Path);ap.add_argument('document',type=Path);ap.add_argument('--steps',type=int,default=0,help='append this many greedy-generated bytes');a=ap.parse_args();torch.set_num_threads(4)
    decoder=PositionalDecoder(a.exe.resolve(),a.bundle);t=time.perf_counter();generated=bytearray()
    try:
        decoder.observe(a.document.read_bytes());prefill=time.perf_counter()-t;ms=[]
        for i in range(a.steps+1):
            t=time.perf_counter();p,info=decoder.predict();byte=int(p.argmax());
            if i<a.steps: decoder.observe(bytes([byte]));generated.append(byte)
            ms.append(1000*(time.perf_counter()-t))
        print(json.dumps(dict(generated_hex=generated.hex(),next_byte_hex=f'{byte:02x}',next_probability=float(p[byte]),prefill_s=prefill,step_ms=ms,last=info),indent=2))
    finally: decoder.close()

if __name__=='__main__':main()
