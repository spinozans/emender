"""Audit the retained panel and clocks; no model imports, corpus, native worker or GPU."""
import json
import math
from pathlib import Path
from statistics import mean, median

ROOT = Path(__file__).with_name('receipts')/'w1'
ARMS = ('rebuilt','static','direct_cpu')


def load(path):
    return json.loads((ROOT/path).read_text())


def check(ok, msg):
    if not ok:
        raise ValueError(msg)


def vector(obj, n):
    a = [obj['default']]*n
    used = set()
    for i,v in obj['other']:
        check(type(i) is int and 0 <= i < n and i not in used,'invalid sparse encoding')
        a[i] = v; used.add(i)
    return a


def audit():
    c,g,t = load('cpu/cpu.json'),load('gpu/parity.json'),load('gpu/timing.json')
    check(c['state']==g['state'] and c['ref']==g['ref']==t['ref'], 'different weights or revisions')
    maxerr=0.
    for run in (c,g):
        cases=run['trace']['cases']; check(len(cases)==8,'panel size')
        for i,case in enumerate(cases):
            w=i//4; fav,other=(b'd',b'c') if not w else (b'c',b'd'); match=(i%4)<2; erase=bool(i%2)
            obs=fav if match else other; key=b'retry_'
            check((case['world'],bytes.fromhex(case['observed']),case['erased'])==(w,obs,erase),'panel identity/order')
            check(len(case['steps'])==2,'step count')
            for s,step in enumerate(case['steps']):
                seq = [key,key+fav] if not s else [] if match else [key+obs]
                arch = [r for r in step['requests'] if r['source']=='archive']
                check([bytes.fromhex(r['key']) for r in arch]==seq,'wrong archive operands')
                visible=key+(obs if s else b'')
                check(all(bytes.fromhex(v['recent'])==visible and v['visible']==len(visible) for v in step['views']),
                      'hypothetical bytes in transcript')
                check(step['handles']==[(key+fav).hex(),(key+other).hex()],'bookmark identities')
                # Exact four-document counts, independent of the native encoder or model.
                if not s:
                    hist=vector(arch[0]['h'],257); child=vector(arch[1]['h'],257)
                    check(hist[fav[0]]==3 and hist[other[0]]==1 and sum(hist)==4,'parent counts')
                    check(child[101]==2 and child[97]==1 and sum(child)==3,'child counts')
                    h={fav[0]:3/4,other[0]:1/4}
                else:
                    h={101:2/3,97:1/3} if match and not erase else {}
                    if not match:
                        end=vector(arch[0]['h'],257); check(end[-1]==1 and sum(end)==1,'structural END')
                p=vector(step['prob'],256)
                check(all(math.isfinite(v) and v>0 for v in p) and abs(sum(p)-1)<3e-5,'byte distribution')
                maxerr=max(maxerr,max(abs(v-(1/256+4*h.get(b,0))/(5 if h else 1)) for b,v in enumerate(p)))
    check(maxerr<=3e-5,'trace disagrees with analytic probability')
    samples=[json.loads(line) for line in (ROOT/'gpu/samples.jsonl').read_text().splitlines()]
    expected=[(block,i,arm) for block,n in [('warmup',4),('primary',32),('diagnostic',8)] for i in range(n)
              for arm in ARMS[i%3:]+ARMS[:i%3]]
    check([(r['block'],r['pair_index'],r['arm']) for r in samples]==expected,'incomplete or reordered timing cells')
    for r in samples:
        w=r['pair_index']%2; arm=r['arm']
        check((r['world'],r['generated'])==(w,(b'ce' if w else b'de').hex()),'unmatched generated bytes')
        check(r['passes']==({'rebuilt':[3,2],'static':[2,2],'direct_cpu':[0,0]}[arm]),'wrong pass budget')
        check(r['rpcs']==([5,3] if arm=='rebuilt' else [4,4]),'unmatched total native calls')
        check(len(r['byte_ns'])==2 and min(r['byte_ns'])>0 and r['pair_ns']>=sum(r['byte_ns']),'broken clocks')
    report={}
    for arm in ARMS:
        ns=[r['pair_ns'] for r in samples if r['block']=='primary' and r['arm']==arm]
        for stat,value in [('p50_ms',median(ns)/1e6),('mean_ms',mean(ns)/1e6)]:
            check(abs(value-t['arms'][arm]['pair'][stat])<1e-9,'incorrect reported time')
        report[arm]=median(ns)/1e6
    def lease(name):
        return dict(s.split('=',1) for s in (ROOT/'gpu'/name).read_text().splitlines())
    first,last,release=lease('initial'),lease('last'),lease('released')
    check(all(first[k]==last[k]==g['lease'][k] for k in ('pid','starttime','gpu','host','created')) and
          first['gpu'] in ('0','1') and int(last['heartbeat'])>int(first['heartbeat']) and release['rc']=='0','lease')
    charge=int(release['released_epoch'])-int(first['created'])+1
    check(0<charge<=180,'resource cap')
    return dict(analytic_max_error=maxerr,cases_per_device=8,complete_pairs={
        'warmup':12,'primary':96,'diagnostic':24},pair_p50_ms=report,card_s_upper=charge)


if __name__=='__main__':
    print(json.dumps(audit(),indent=2))
